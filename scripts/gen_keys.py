# -*- coding: utf-8 -*-
"""Generate the offline license signing keypair.

The private key stays in secrets/ and must never be committed or shared.
The public key is embedded in the static app so licenses can be verified
without a server.
"""
from __future__ import annotations

import base64
import datetime as dt
import json
import pathlib
import sys

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec

BASE = pathlib.Path(__file__).resolve().parent.parent
SECRETS = BASE / "secrets"
PUBLIC_JS = BASE / "assets" / "js" / "license-public.js"
PRIVATE_KEY = SECRETS / "license_private.pem"


def b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def sign_payload(private_key: ec.EllipticCurvePrivateKey, payload: dict) -> str:
    raw = json.dumps(payload, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode("utf-8")
    signature = private_key.sign(raw, ec.ECDSA(hashes.SHA256()))
    return f"MH1.{b64url(raw)}.{b64url(signature)}"


def main() -> None:
    SECRETS.mkdir(exist_ok=True)
    if PRIVATE_KEY.exists() and "--force" not in sys.argv:
        print("Private key already exists. Use --force to rotate (invalidates old licenses).")
        return

    private_key = ec.generate_private_key(ec.SECP256R1())
    pem = private_key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption(),
    )
    PRIVATE_KEY.write_bytes(pem)
    try:
        PRIVATE_KEY.chmod(0o600)
    except OSError:
        pass

    public_der = private_key.public_key().public_bytes(
        encoding=serialization.Encoding.DER,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    )
    PUBLIC_JS.write_text(
        "/* Generated by scripts/gen_keys.py. Public key only. */\n"
        f'window.MH_LICENSE_PUBLIC_KEY = "{base64.b64encode(public_der).decode("ascii")}";\n',
        encoding="utf-8",
    )

    demo_payload = {
        "v": 1,
        "plan": "pro",
        "email": "demo@maemulhanjang.com",
        "name": "데모 라이선스",
        "issued": dt.date.today().isoformat(),
        "exp": "2035-12-31",
        "order": "DEMO",
    }
    demo = sign_payload(private_key, demo_payload)
    (SECRETS / "demo-license.txt").write_text(demo + "\n", encoding="utf-8")
    (SECRETS / "license-public.txt").write_text(
        base64.b64encode(public_der).decode("ascii") + "\n", encoding="utf-8"
    )

    print("Created", PRIVATE_KEY)
    print("Created", PUBLIC_JS)
    print("Demo license written to", SECRETS / "demo-license.txt")
    print("Keep secrets/license_private.pem safe. Back it up offline.")


if __name__ == "__main__":
    main()
